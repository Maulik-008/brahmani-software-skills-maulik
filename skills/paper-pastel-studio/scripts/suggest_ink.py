#!/usr/bin/env python3
"""Generate AA-safe text variants ("ink") of the six category hues and the status colours.

The default system uses chip-* for glyphs AND small labels. Measured against
tokens.css, small chip text on its own tint falls under 4.5:1 for several hues.
This keeps each hue and saturation and lowers lightness (light theme) until the
text passes 4.5:1 on background, surface-1, surface-2, its tint, and the
white/70 pill over its tint. Dark theme is only touched if a pair fails.

  python3 suggest_ink.py path/to/tokens.css > a11y-text.css
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from contrast import parse_blocks, hsl_to_rgb, blend, ratio, CATS

TARGET = 4.55  # AA is 4.5; the extra 0.05 absorbs 8-bit rounding differences between browsers

def fmt(h, s, l):
    return f'{h:g} {s:g}% {l:.1f}%'.replace('.0%', '%')

def targets(t, theme, hue):
    g = lambda n: hsl_to_rgb(*t[n])
    tint = g(f'tint-{hue}')
    base = (1, 1, 1) if theme == 'light' else (0, 0, 0)
    a = 0.7 if theme == 'light' else 0.2
    chip = g(f'accent-{hue}')
    # also the common "pill with a 10-15% fill of its own colour" (bg-chip-x/10, /15) on canvas and bands
    fills = [blend(chip, b, al) for b in (g('background'), g('surface-1')) for al in (0.10, 0.15)]
    return [g('background'), g('surface-1'), g('surface-2'), tint, blend(base, tint, a)] + fills

def solve(t, theme, hue, key):
    h, s, l = t[key]
    bgs = targets(t, theme, hue)
    step = -0.5 if theme == 'light' else 0.5
    cur = l
    for _ in range(120):
        rgb = hsl_to_rgb(h, s, cur)
        if min(ratio(rgb, b) for b in bgs) >= TARGET:
            break
        cur = max(0, min(100, cur + step))
    return (h, s, cur), min(ratio(hsl_to_rgb(h, s, cur), b) for b in bgs)

def main():
    css = open(sys.argv[1], encoding='utf-8').read()
    th = parse_blocks(css)
    out = ['/* AA-safe text variants. Generated by scripts/suggest_ink.py from tokens.css.',
           '   Use ONLY for text (labels, eyebrows, stat numbers). Keep chip-* for glyphs',
           '   and icon-chip fills. Paste after tokens.css. Same hues, darker lightness. */',
           '@layer base {']
    for theme, sel in (('light', ':root'), ('dark', '.dark')):
        out.append(f'  {sel} {{')
        for c in CATS:
            v, worst = solve(th[theme], theme, c, f'accent-{c}')
            out.append(f'    --chip-{c}-ink: {fmt(*v)};  /* worst pair {worst:.2f}:1 */')
        # status text (warning, destructive, success): solved against bg, surface-1 and its own 5-6% callout wash
        t = th[theme]
        for st in ('warning', 'destructive', 'success'):
            bg0, s1 = hsl_to_rgb(*t['background']), hsl_to_rgb(*t['surface-1'])
            col = hsl_to_rgb(*t[st])
            s2 = hsl_to_rgb(*t['surface-2'])
            # callouts sit on the canvas OR on a surface-1/2 band, so solve against the wash over all three
            bgs = [bg0, s1] + [blend(col, base_, a) for base_ in (bg0, s1, s2) for a in (0.05, 0.06)]
            h, s_, l = t[st]; cur = l; step = -0.5 if theme == 'light' else 0.5
            for _ in range(120):
                if min(ratio(hsl_to_rgb(h, s_, cur), b) for b in bgs) >= TARGET: break
                cur += step
            out.append(f'    --{st}-ink: {fmt(h, s_, cur)};')
        out.append('  }')
    out.append('}')
    print('\n'.join(out))

if __name__ == '__main__':
    main()
